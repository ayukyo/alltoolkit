%% TEMPERATURE CONVERSION
function result = convert_temperature(value, from_unit, to_unit)
    % Temperature is special - not a simple multiplication
    % First convert to Celsius, then to target unit
    
    % Normalize unit names
    from_unit = lower(strtrim(from_unit));
    to_unit = lower(strtrim(to_unit));
    
    valid_units = {'c', 'celsius', 'f', 'fahrenheit', 'k', 'kelvin'};
    if ~any(strcmp(from_unit, valid_units)) || ~any(strcmp(to_unit, valid_units))
        error('unit_converter_utils:InvalidTemperatureUnit', ...
            'Invalid temperature unit. Valid units: c, celsius, f, fahrenheit, k, kelvin');
    end
    
    % Convert to Celsius first
    celsius_value = to_celsius(value, from_unit);
    
    % Convert from Celsius to target
    result = from_celsius(celsius_value, to_unit);
end

function celsius = to_celsius(value, from_unit)
    switch from_unit
        case {'c', 'celsius'}
            celsius = value;
        case {'f', 'fahrenheit'}
            celsius = (value - 32) * 5/9;
        case {'k', 'kelvin'}
            celsius = value - 273.15;
        otherwise
            error('unit_converter_utils:InvalidFromUnit', 'Unknown temperature unit: %s', from_unit);
    end
end

function result = from_celsius(celsius, to_unit)
    switch to_unit
        case {'c', 'celsius'}
            result = celsius;
        case {'f', 'fahrenheit'}
            result = celsius * 9/5 + 32;
        case {'k', 'kelvin'}
            result = celsius + 273.15;
        otherwise
            error('unit_converter_utils:InvalidToUnit', 'Unknown temperature unit: %s', to_unit);
    end
end

