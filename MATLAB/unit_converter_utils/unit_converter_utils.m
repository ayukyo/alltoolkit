%% HELPER FUNCTION
function [from_factor, to_factor] = get_factors(factors, from_unit, to_unit, category)
    % Get conversion factors from struct
    from_factor = get_field_safe(factors, from_unit);
    to_factor = get_field_safe(factors, to_unit);
    
    if isempty(from_factor)
        error('unit_converter_utils:InvalidFromUnit', ...
            'Unknown %s unit: %s', category, from_unit);
    end
    if isempty(to_factor)
        error('unit_converter_utils:InvalidToUnit', ...
            'Unknown %s unit: %s', category, to_unit);
    end
end

function value = get_field_safe(s, name)
    % Safely get field value, return empty if not found
    value = [];
    if isfield(s, name)
        value = s.(name);
    end
end

